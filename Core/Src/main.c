/**
  * @brief TIM Update Interrupt Callback - Updates CCR1, CCR2, CCR3 every PWM cycle
  */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  if (htim->Instance == TIM1)
  {
    /* Advance 32-bit phase accumulator */
    phase_accumulator += phase_step;

    /* Compute 3-phase angles separated by 120 degrees */
    uint32_t pA = phase_accumulator;
    uint32_t pB = phase_accumulator + PHASE_120_DEG;
    uint32_t pC = phase_accumulator + PHASE_240_DEG;

    /* Extract table indices (top 8 bits for 256-entry table) */
    uint8_t idxA = (uint8_t)(pA >> 24);
    uint8_t idxB = (uint8_t)(pB >> 24);
    uint8_t idxC = (uint8_t)(pC >> 24);

    /* Update compare registers directly */
    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, sine_table[idxA]);
    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_2, sine_table[idxB]);
    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_3, sine_table[idxC]);
  }
}
